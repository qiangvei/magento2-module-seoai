<?php
declare(strict_types=1);

namespace Qiangvei\SeoAi\Model;

use Magento\Store\Model\StoreManagerInterface;
use Qiangvei\SeoAi\Api\RobotsBuilderInterface;
use Qiangvei\SeoAi\Helper\Config;

/**
 * Renders robots.txt from the module configuration.
 *
 * Order of the document:
 *  1. Generator comment header
 *  2. AI crawler directives (User-agent + Disallow for every blocked bot)
 *  3. Conventional SEO crawl rules
 *  4. Optional llms.txt pointer comment (when configured)
 *
 * Custom/override content supplied via the "seoai/geo/custom_rules" store
 * config path is appended verbatim when present (placeholder: empty by default).
 */
class RobotsBuilder implements RobotsBuilderInterface
{
    /** Conventional paths disallowed for all crawlers. */
    private const DEFAULT_DISALLOW = [
        '/checkout/',
        '/customer/',
        '/sendfriend/',
        '/catalogsearch/',
        '/wishlist/',
        '/compare/',
        '/review/',
        '/sales/',
        '/download/',
        '/newsletter/',
        '/giftcard/',
        '/paypal/',
        '/authorizenet/',
        '/index.php/',
    ];

    private Config $config;

    private StoreManagerInterface $storeManager;

    /**
     * Config-field suffixes keyed by bot slug, injected from di.xml.
     *
     * @var array<string, string>
     */
    private array $knownBots;

    /**
     * User-agent strings keyed by bot slug, injected from di.xml.
     *
     * @var array<string, string>
     */
    private array $botUserAgents;

    public function __construct(
        Config $config,
        StoreManagerInterface $storeManager,
        array $knownBots = [],
        array $botUserAgents = []
    ) {
        $this->config = $config;
        $this->storeManager = $storeManager;
        $this->knownBots = $knownBots;
        $this->botUserAgents = $botUserAgents;
    }

    /**
     * @inheritdoc
     */
    public function build(): string
    {
        $store = (string) $this->storeManager->getStore()->getCode();
        $lines = [
            '# robots.txt generated by Qiangvei_SeoAi module',
            '# AI crawler policy is managed from Stores > Configuration > SeoAi > GEO.',
            '',
        ];

        foreach ($this->config->getAiBotPolicies($store) as $userAgent => $blocked) {
            if (!$blocked) {
                continue;
            }
            $lines[] = 'User-agent: ' . $userAgent;
            $lines[] = 'Disallow: /';
            $lines[] = '';
        }

        $lines[] = 'User-agent: *';
        foreach (self::DEFAULT_DISALLOW as $path) {
            $lines[] = 'Disallow: ' . $path;
        }
        $lines[] = '';

        if ($this->config->isLlmsLinkInRobots($store) && $this->config->isLlmsEnabled($store)) {
            $lines[] = '# AI content index';
            $lines[] = '# Learn more: https://llmstxt.org/';
            $lines[] = '# llms.txt: ' . $this->buildLlmsUrl();
            $lines[] = '';
        }

        $custom = trim((string) $this->config->getValue('geo/custom_rules', $store));
        if ($custom !== '') {
            $lines[] = '# Custom rules';
            foreach (preg_split('/\R+/', $custom) ?: [] as $rule) {
                $rule = trim($rule);
                if ($rule !== '') {
                    $lines[] = $rule;
                }
            }
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * Absolute URL of the llms.txt endpoint for the current store.
     */
    private function buildLlmsUrl(): string
    {
        try {
            $baseUrl = rtrim((string) $this->storeManager->getStore()->getBaseUrl(), '/');
        } catch (\Throwable) {
            $baseUrl = '';
        }

        return $baseUrl !== '' ? $baseUrl . '/seoai/llms/index' : '/seoai/llms/index';
    }
}
